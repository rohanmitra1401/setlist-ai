"use server";

import { getServerSession } from "next-auth";
import { authOptions } from "@/app/api/auth/[...nextauth]/route";
import { fetchPlaylistTracks } from "@/lib/setlist-engine";
import SpotifyWebApi from "spotify-web-api-node";

export async function createPlaylistAction(name: string, trackUris: string[]) {
    try {
        const session = await getServerSession(authOptions);

        if (!session || !session.accessToken) {
            return { success: false, error: "Unauthorized" };
        }

        const spotifyApi = new SpotifyWebApi({
            accessToken: session.accessToken,
        });

        // 1. Get User ID
        const me = await spotifyApi.getMe();
        const userId = me.body.id;

        // 2. Create Playlist
        const playlist = await spotifyApi.createPlaylist(name, {
            description: "Generated by Setlist AI",
            public: false,
        });

        if (!playlist.body.id) {
            throw new Error("Failed to create playlist");
        }

        // 3. Add Tracks
        // API limit is 100 tracks per request, but we only have 30 max so one call is fine
        if (trackUris.length > 0) {
            await spotifyApi.addTracksToPlaylist(playlist.body.id, trackUris);
        }

        return { success: true, playlistId: playlist.body.id, url: playlist.body.external_urls.spotify };
    } catch (e: any) {
        console.error("Create playlist error:", e);
        return { success: false, error: e.message || "Failed to create playlist" };
    }
}

// Output: Raw tracks (no features yet)
export async function fetchPlaylistTracksAction(
    playlistUrl: string,
    accessToken?: string // Optional, if we have it client side, or we get it here
) {
    let token = accessToken;
    if (!token) {
        const session = await getServerSession(authOptions);
        if (!session?.accessToken) {
            throw new Error("Unauthorized");
        }
        token = session.accessToken;
    }

    // Extract ID from URL
    let playlistId = "";
    if (playlistUrl.includes("spotify:playlist:")) {
        playlistId = playlistUrl.split(":")?.pop() || "";
    } else {
        try {
            const url = new URL(playlistUrl);
            const parts = url.pathname.split("/");
            playlistId = parts[2] || parts[1];
        } catch (e) {
            playlistId = playlistUrl;
        }
    }

    if (!playlistId) {
        throw new Error("Invalid Playlist URL");
    }

    // Use shared engine fetcher
    return await fetchPlaylistTracks(playlistId, token);
}
